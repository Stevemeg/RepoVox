#!/usr/bin/env bash
# Start the RepoVox Compose stack on one Linux host with the hardened overlay.
#
#   scripts/deploy_selfhosted.sh [--mode local|production]        Prerequisites, .env, start.
#   scripts/deploy_selfhosted.sh --check [--mode local|production] Preflight only; needs no
#                                          running Docker daemon.
#   scripts/deploy_selfhosted.sh --repair-env   Append missing generated keys to .env.
#
# --mode local (default): development identities on http://localhost:3000, this host only.
# --mode production: GitHub OAuth sign-in for provisioned accounts behind a TLS reverse proxy;
#   .env must set REPOVOX_ORIGIN (https://...), REPOVOX_GITHUB_CLIENT_ID and
#   REPOVOX_GITHUB_CLIENT_SECRET. Secret values are never printed.
# See docs/operations/deployment-guide.md.
set -euo pipefail
umask 077

ROOT=$(cd "$(dirname "$0")/.." && pwd)
cd "$ROOT"

BASE=docker-compose.yml
OVERLAY=infrastructure/local/docker-compose.prod.yml
PRODUCTION=infrastructure/local/docker-compose.production.yml
TIMEOUT=${DEPLOY_TIMEOUT:-600}
# Every credential docker-compose.yml requires: random values, and two fixed identifiers.
SECRET_KEYS=(
  POSTGRES_PASSWORD MIGRATION_PASSWORD APP_DATABASE_PASSWORD WORKER_DATABASE_PASSWORD
  MEDIA_MIGRATION_PASSWORD MEDIA_APP_PASSWORD MEDIA_WORKER_PASSWORD SESSION_SECRET
  MINIO_ROOT_PASSWORD STORAGE_SECRET_KEY
)
NAME_KEYS=(MINIO_ROOT_USER STORAGE_ACCESS_KEY)
NAME_VALUES=(repovox-local-admin repovox-local-service)
# Set by the operator for --mode production; the script never generates them.
PRODUCTION_KEYS=(REPOVOX_ORIGIN REPOVOX_GITHUB_CLIENT_ID REPOVOX_GITHUB_CLIENT_SECRET)
REQUIRED_FILES=(
  "$BASE" "$OVERLAY" "$PRODUCTION"
  infrastructure/local/api.Dockerfile infrastructure/local/web.Dockerfile
  infrastructure/local/init-db.sh
  tools/phase1_storage_config.py tools/phase1_storage_init.py
  apps/api/alembic.ini apps/api/alembic_media.ini
  apps/web/package.json apps/web/package-lock.json
)
LONG_RUNNING=(postgres redis storage api web worker dispatcher media-worker)
CHECKED=(worker dispatcher media-worker)
SETTINGS_SERVICES=(api worker dispatcher media-worker)

failures=0
ok() { printf 'ok    %s\n' "$*"; }
warn() { printf 'warn  %s\n' "$*"; }
fail() {
  printf 'FAIL  %s\n' "$*"
  failures=$((failures + 1))
}
die() {
  printf 'error: %s\n' "$*" >&2
  exit 1
}

usage() {
  sed -n '2,13p' "$0" | sed 's/^# \{0,1\}//'
}

compose_files() {
  # $1: local or production
  printf '%s\n' -f "$BASE" -f "$OVERLAY"
  if [ "$1" = production ]; then printf '%s\n' -f "$PRODUCTION"; fi
}

random_hex() {
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -hex 32
  elif command -v python3 >/dev/null 2>&1; then
    python3 -c 'import secrets; print(secrets.token_hex(32))'
  else
    return 1
  fi
}

# Print KEY=value lines for the generated keys named in "$@" (to a file, never the terminal).
generated() {
  local key value i
  for key in "$@"; do
    for i in "${!NAME_KEYS[@]}"; do
      if [ "${NAME_KEYS[$i]}" = "$key" ]; then
        printf '%s=%s\n' "$key" "${NAME_VALUES[$i]}"
        continue 2
      fi
    done
    if ! value=$(random_hex); then
      die "neither openssl nor python3 is available to generate secrets"
    fi
    printf '%s=%s\n' "$key" "$value"
  done
}

# Write a new env file at $1. Never replaces an existing file; values never reach stdout.
write_env() {
  local dest=$1 tmp
  [ ! -e "$dest" ] || die "$dest already exists; it is kept as is"
  # Checked first, so a half-written temporary file can never be left behind.
  random_hex >/dev/null || die "neither openssl nor python3 is available to generate secrets"
  tmp=$(mktemp "$dest.XXXXXX")
  chmod 600 "$tmp"
  {
    printf '# Generated by scripts/deploy_selfhosted.sh on %s.\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
    printf '# Private to this host: never commit, paste or copy it elsewhere.\n'
    generated "${SECRET_KEYS[@]}" "${NAME_KEYS[@]}"
  } >"$tmp" || {
    rm -f "$tmp"
    exit 1
  }
  mv -n "$tmp" "$dest" || true # -n never replaces a file; some mv versions then exit 1.
  if [ -e "$tmp" ]; then
    rm -f "$tmp"
    die "$dest appeared while it was being written; it is kept as is"
  fi
}

# Append every missing generated key to an existing env file $1. Existing keys are untouched.
repair_env() {
  local file=$1 key count missing=() block
  [ -f "$file" ] || die "$file does not exist; run without --repair-env to generate it"
  for key in "${SECRET_KEYS[@]}" "${NAME_KEYS[@]}"; do
    count=$(grep -c "^$key=" "$file" || true)
    [ "$count" -le 1 ] || die "$file sets $key $count times; remove the duplicates by hand first"
    [ "$count" = 1 ] || missing+=("$key")
  done
  if [ "${#missing[@]}" -eq 0 ]; then
    ok "$file already holds every generated key; nothing changed"
    return 0
  fi
  block=$(generated "${missing[@]}") # Held in memory, then appended; never printed.
  if [ -s "$file" ] && [ -n "$(tail -c 1 "$file")" ]; then printf '\n' >>"$file"; fi
  {
    printf '# Added by scripts/deploy_selfhosted.sh --repair-env on %s.\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
    printf '%s\n' "$block"
  } >>"$file"
  chmod 600 "$file"
  ok "added ${missing[*]} to $file with new random values (values not shown); mode set to 600"
}

# Check that env file $1 holds every generated key once. Reports key names only.
check_env() {
  local file=$1 key count value secrets=() repeated
  for key in "${SECRET_KEYS[@]}" "${NAME_KEYS[@]}"; do
    count=$(grep -c "^$key=" "$file" || true)
    if [ "$count" != 1 ]; then
      fail "$file: $key is set $count times, expected once"
      continue
    fi
    value=$(grep "^$key=" "$file" | cut -d= -f2-)
    [ -n "$value" ] || fail "$file: $key is empty"
  done
  for key in "${SECRET_KEYS[@]}"; do
    grep -q "^$key=" "$file" || continue # Already reported above.
    value=$(grep "^$key=" "$file" | head -n 1 | cut -d= -f2-)
    [ "${#value}" -ge 32 ] || fail "$file: $key is shorter than 32 characters"
    secrets+=("$value")
  done
  [ "${#secrets[@]}" -gt 0 ] || return 0
  repeated=$(printf '%s\n' "${secrets[@]}" | sort | uniq -d | wc -l | tr -d ' ')
  [ "$repeated" = 0 ] || fail "$file: $repeated secret values are reused across keys"
}

# Check the operator-set production keys in env file $1. Prints the origin, never a secret.
check_production_env() {
  local file=$1 key count value
  for key in "${PRODUCTION_KEYS[@]}"; do
    count=$(grep -c "^$key=" "$file" || true)
    if [ "$count" != 1 ]; then
      fail "$file: $key is set $count times; --mode production needs it exactly once"
      continue
    fi
    value=$(grep "^$key=" "$file" | cut -d= -f2-)
    case "$key" in
      REPOVOX_ORIGIN)
        if [[ "$value" =~ ^https://[a-z0-9]([a-z0-9.-]*[a-z0-9])?(:[0-9]{1,5})?$ ]]; then
          ok "REPOVOX_ORIGIN is $value"
        else
          fail "$file: REPOVOX_ORIGIN must be an exact lowercase https://host[:port], no path"
        fi
        ;;
      REPOVOX_GITHUB_CLIENT_ID)
        [ -n "$value" ] || fail "$file: REPOVOX_GITHUB_CLIENT_ID is empty"
        ;;
      REPOVOX_GITHUB_CLIENT_SECRET)
        [ "${#value}" -ge 20 ] || fail "$file: REPOVOX_GITHUB_CLIENT_SECRET is missing or too short"
        ;;
    esac
  done
}

# Service names under the top-level `services:` of a Compose file.
services_of() {
  awk '/^[^ #]/ { s = ($0 ~ /^services:/); next }
       s && /^  [A-Za-z0-9_.-]+:/ { n = $1; sub(/:$/, "", n); print n }' "$1"
}

# The lines of one service's block in a Compose file.
block() {
  awk -v name="$2" '/^[^ #]/ { s = ($0 ~ /^services:/); current = ""; next }
       s && /^  [A-Za-z0-9_.-]+:/ { current = $1; sub(/:$/, "", current); next }
       s && current == name { print }' "$1"
}

compose_structure() {
  local base overlay production service lines start=$failures
  base=$(services_of "$BASE")
  overlay=$(services_of "$OVERLAY")
  for service in $overlay; do
    grep -qx "$service" <<<"$base" || fail "$OVERLAY names $service, which $BASE does not define"
  done
  for service in "${LONG_RUNNING[@]}"; do
    grep -qx "$service" <<<"$base" || fail "$BASE does not define $service"
    lines=$(block "$OVERLAY" "$service")
    grep -q 'restart: unless-stopped' <<<"$lines" || fail "$OVERLAY: $service has no restart: unless-stopped"
  done
  for service in "${CHECKED[@]}"; do
    lines=$(block "$OVERLAY" "$service")
    grep -q 'healthcheck:' <<<"$lines" || fail "$OVERLAY: $service has no healthcheck"
  done
  lines=$(block "$OVERLAY" web)
  grep -q 'read_only: true' <<<"$lines" || fail "$OVERLAY: web is not read_only"
  grep -q 'cap_drop: \[ALL\]' <<<"$lines" || fail "$OVERLAY: web keeps capabilities"
  grep -q 'no-new-privileges:true' <<<"$lines" || fail "$OVERLAY: web lacks no-new-privileges"
  grep -q "'/web/.next/cache:" <<<"$lines" || fail "$OVERLAY: web has no writable /web/.next/cache"
  if grep -v '^ *#' "$OVERLAY" | grep -q 'REPOVOX_'; then
    fail "$OVERLAY sets a REPOVOX_ setting; the hardening overlay must only harden containers"
  fi
  # The production overlay: production settings for every service that reads them.
  production=$(services_of "$PRODUCTION")
  for service in "${SETTINGS_SERVICES[@]}"; do
    grep -qx "$service" <<<"$production" || fail "$PRODUCTION does not configure $service"
  done
  for expected in "REPOVOX_ENVIRONMENT: production" "REPOVOX_DEV_AUTH: 'false'" \
    "REPOVOX_FIXTURES: 'false'" "REPOVOX_AUTH_PROVIDER: github" '${REPOVOX_ORIGIN:?' \
    '${REPOVOX_GITHUB_CLIENT_ID:?' '${REPOVOX_GITHUB_CLIENT_SECRET:?'; do
    grep -qF "$expected" "$PRODUCTION" || fail "$PRODUCTION lacks $expected"
  done
  [ "$failures" -gt "$start" ] ||
    ok "Compose structure: hardening overlay ($(wc -w <<<"$overlay" | tr -d ' ') services) and production overlay ($(wc -w <<<"$production" | tr -d ' ') services) are consistent with $BASE"
}

compose_keys() {
  local wanted have
  wanted=$(grep -o '\${[A-Z_]*:?' "$BASE" | sed 's/^\${//; s/:?$//' | sort -u)
  have=$(printf '%s\n' "${SECRET_KEYS[@]}" "${NAME_KEYS[@]}" | sort -u)
  if [ "$wanted" = "$have" ]; then
    ok "secret keys match the $(printf '%s\n' "$wanted" | wc -l | tr -d ' ') variables $BASE requires"
  else
    fail "secret keys differ from $BASE: $(diff <(printf '%s\n' "$wanted") <(printf '%s\n' "$have") | grep '^[<>]' | tr '\n' ' ')"
  fi
}

# $1: "required" fails on a missing prerequisite, "advisory" only warns.
prerequisites() {
  local report=warn version major
  [ "$1" != required ] || report=fail
  if [ "$(uname -s)" = Linux ]; then ok "Linux $(uname -r)"; else $report "not Linux ($(uname -s)); parser containment needs Linux"; fi
  case "$(uname -m)" in
    x86_64 | aarch64) ok "machine $(uname -m)" ;;
    *) $report "machine $(uname -m); parser containment supports x86_64 and aarch64 only" ;;
  esac
  if [ -r /sys/kernel/security/lsm ] && grep -qw landlock /sys/kernel/security/lsm; then
    ok "Landlock is an active security module"
  else
    $report "Landlock is not listed in /sys/kernel/security/lsm"
  fi
  if command -v docker >/dev/null 2>&1; then
    ok "Docker CLI $(docker --version 2>/dev/null | sed 's/^Docker version //')"
    version=$(docker compose version --short 2>/dev/null || true)
    major=${version#v}
    major=${major%%.*}
    if [ -n "$major" ] && [ "$major" -ge 2 ] 2>/dev/null; then
      ok "Docker Compose $version"
    else
      $report "Docker Compose v2 is not available ('docker compose version')"
    fi
    if [ "$1" = required ]; then
      if docker info >/dev/null 2>&1; then ok "Docker daemon reachable"; else fail "Docker daemon not reachable"; fi
    fi
  else
    $report "Docker is not installed"
  fi
  if command -v curl >/dev/null 2>&1; then ok "curl present"; else $report "curl is needed to poll health"; fi
}

CHECK_TMP=""
cleanup() {
  [ -z "$CHECK_TMP" ] || rm -rf "$CHECK_TMP"
}

run_check() {
  local file tmp before report files mode
  printf 'Preflight for %s, mode %s (no Docker daemon needed)\n' "$ROOT" "$MODE"
  for file in "${REQUIRED_FILES[@]}"; do
    [ -f "$file" ] || fail "missing $file"
  done
  [ "$failures" -gt 0 ] || ok "${#REQUIRED_FILES[@]} required files present"
  compose_keys
  CHECK_TMP=$(mktemp -d)
  trap cleanup EXIT
  tmp=$CHECK_TMP
  write_env "$tmp/.env"
  before=$failures
  check_env "$tmp/.env"
  if [ "$(uname -s)" = Linux ] && [ "$(stat -c %a "$tmp/.env")" != 600 ]; then
    fail "generated env file is not mode 600"
  fi
  [ "$failures" -gt "$before" ] ||
    ok "secret generation: ${#SECRET_KEYS[@]} distinct random values of 64 hex characters, ${#NAME_KEYS[@]} identifiers (values not shown)"
  # --repair-env on a copy missing three keys restores them and keeps what was there.
  grep -v '^MEDIA_' "$tmp/.env" >"$tmp/partial.env"
  before=$failures
  report=$(repair_env "$tmp/partial.env")
  check_env "$tmp/partial.env"
  if [ "$failures" -eq "$before" ] && cmp -s <(grep -v '^MEDIA_' "$tmp/.env" | grep -v '^#') \
    <(grep -v '^MEDIA_' "$tmp/partial.env" | grep -v '^#'); then
    ok "--repair-env adds missing keys and leaves existing ones unchanged (values not shown)"
  else
    fail "--repair-env did not restore a partial env file correctly"
  fi
  if [ -e .env ]; then
    # Reported as warnings: the preflight checks the repository; a normal run stops instead.
    # check_env runs in a subshell here, so its findings are not counted as failures.
    report=$(check_env .env)
    if [ "$MODE" = production ]; then
      report+=$'
'$(check_production_env .env | grep -v '^ok ' || true)
      report=$(grep -v '^$' <<<"$report" || true)
    fi
    if [ -z "$report" ]; then
      ok "existing .env holds every key mode $MODE needs (values not shown)"
    else
      sed 's/^FAIL /warn /' <<<"$report"
      warn "existing .env is incomplete for mode $MODE: a normal run stops until it is corrected (--repair-env adds generated keys)"
    fi
  else
    ok "no .env yet; a normal run generates it"
  fi
  compose_structure
  if command -v docker >/dev/null 2>&1 && docker compose version >/dev/null 2>&1; then
    # Placeholders for the operator-set keys, so the production overlay can be resolved too.
    printf 'REPOVOX_ORIGIN=https://repovox.invalid\nREPOVOX_GITHUB_CLIENT_ID=preflight\nREPOVOX_GITHUB_CLIENT_SECRET=%s\n' \
      "$(random_hex)" >>"$tmp/.env"
    for mode in local production; do
      mapfile -t files < <(compose_files "$mode")
      if docker compose --env-file "$tmp/.env" "${files[@]}" config --quiet; then
        ok "docker compose config accepts the $mode files"
      else
        fail "docker compose config rejects the $mode files"
      fi
    done
  else
    warn "Docker Compose not installed here: 'docker compose config' not run"
  fi
  prerequisites advisory
  if [ "$failures" -gt 0 ]; then
    printf '\nPreflight failed: %s problem(s).\n' "$failures"
    exit 1
  fi
  printf '\nPreflight passed.\n'
}

wait_for() {
  local label=$1 url=$2 deadline=$((SECONDS + TIMEOUT))
  until curl -fs -o /dev/null --max-time 5 "$url"; do
    if [ "$SECONDS" -ge "$deadline" ]; then
      fail "$label did not answer at $url within ${TIMEOUT}s"
      return 1
    fi
    sleep 5
  done
  ok "$label: $url"
}

run_deploy() {
  local files ready origin expected
  printf 'Prerequisites (mode %s)\n' "$MODE"
  prerequisites required
  [ "$failures" -eq 0 ] || die "prerequisites not met"
  if [ -e .env ]; then
    ok ".env exists and is kept"
  else
    write_env .env
    ok ".env generated with mode 600 (values not shown)"
  fi
  check_env .env
  [ "$failures" -eq 0 ] || die ".env is incomplete; run with --repair-env, or move it aside to regenerate"
  if [ "$MODE" = production ]; then
    check_production_env .env
    [ "$failures" -eq 0 ] || die ".env lacks valid production settings; see docs/operations/deployment-guide.md"
  fi
  mapfile -t files < <(compose_files "$MODE")
  docker compose "${files[@]}" config --quiet
  printf 'Building and starting the stack\n'
  docker compose "${files[@]}" up -d --build
  wait_for "API liveness" http://127.0.0.1:8000/health || true
  wait_for "API readiness" http://127.0.0.1:8000/ready || true
  wait_for "web" http://127.0.0.1:3000/sign-in || true
  docker compose "${files[@]}" ps
  if [ "$failures" -gt 0 ]; then
    printf '\nThe stack did not become ready. Inspect: docker compose %s logs --tail 200\n' "${files[*]}" >&2
    exit 1
  fi
  ready=$(curl -fsS --max-time 5 http://127.0.0.1:8000/ready)
  printf 'API readiness: %s\n' "$ready"
  expected=development
  [ "$MODE" = local ] || expected=production
  grep -q "\"environment\":\"$expected\"" <<<"$ready" || die "the API is not running in $expected mode"
  if [ "$MODE" = local ]; then
    cat <<'EOF'

RepoVox is running on this host with the development identity adapter (--mode local).
  Web: http://localhost:3000   (the API accepts only http://localhost:3000 or http://127.0.0.1:3000)
  API: http://127.0.0.1:8000/health and http://127.0.0.1:8000/ready (loopback only)

From another machine, tunnel the web port instead of publishing it:
  ssh -N -L 3000:127.0.0.1:3000 <user>@<this-host>    then open http://localhost:3000

For a public HTTPS deployment with GitHub sign-in, use --mode production.
EOF
    return 0
  fi
  origin=$(grep '^REPOVOX_ORIGIN=' .env | cut -d= -f2-)
  cat <<EOF

RepoVox is running in production mode with GitHub sign-in (--mode production).
  Public origin:  $origin   (served by your TLS reverse proxy)
  Upstream:       http://127.0.0.1:3000   (the only port the proxy should forward to)
  API:            http://127.0.0.1:8000/health and /ready stay on loopback

1. The GitHub OAuth App's authorization callback URL must be exactly:
     $origin/api/v1/auth/github/callback
2. Allow each person by numeric GitHub id (https://api.github.com/users/<login> shows it):
     docker compose ${files[*]} run --rm migrate \\
       python -m repovox.auth.accounts add --github-id <id> --name "<name>" --email <email>
3. Reverse proxy, for example Caddy (obtains and renews the certificate itself):
     ${origin#https://} {
       reverse_proxy 127.0.0.1:3000
     }
See docs/operations/deployment-guide.md.
EOF
}

MODE=local
ACTION=deploy
while [ "$#" -gt 0 ]; do
  case "$1" in
    --check) ACTION=check ;;
    --repair-env) ACTION=repair ;;
    --mode)
      [ "$#" -ge 2 ] || die "--mode needs local or production"
      MODE=$2
      shift
      ;;
    --mode=*) MODE=${1#--mode=} ;;
    -h | --help)
      usage
      exit 0
      ;;
    *)
      usage >&2
      exit 2
      ;;
  esac
  shift
done
case "$MODE" in
  local | production) ;;
  *) die "--mode must be local or production, not '$MODE'" ;;
esac

case "$ACTION" in
  check) run_check ;;
  repair)
    repair_env .env
    check_env .env
    if [ "$MODE" = production ]; then check_production_env .env; fi
    [ "$failures" -eq 0 ] || exit 1
    ;;
  deploy) run_deploy ;;
esac
